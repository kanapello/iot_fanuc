def upgrade() -> None:
    _run(ORGANIZATIONS_AND_SITES)
    for table in ("areas", "collectors", "machines", "shift_templates"):
        _rekey_site(table)
    _run(MACHINES)

    _run(RAW)
    _rekey_machine("telemetry", reference=False)
    _rekey_machine("machine_events", reference=False)
    _run(RAW_AFTER)

    op.execute("DROP VIEW downtime_annotations_resolved")
    for table in ("downtime_annotations", "scrap_records", "operator_setup_marks"):
        _rekey_machine(table)
    _rekey_machine("programs", nullable=True)
    _run(DERIVED)
    _run(OPERATOR_INPUT_AFTER)
    _run(REFERENCES)
    _run(USERS)
    _run(SEED)


