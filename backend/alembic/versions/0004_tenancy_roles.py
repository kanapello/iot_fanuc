ROLES = "'operator', 'master', 'engineer', 'admin', 'service'"


def _run(script: str) -> None:
    for statement in script.split(";\n"):
        if statement.strip():
            op.execute(statement)


def _rekey_site(table: str) -> None:
    """site_id text (old sites.id) -> site_id integer."""
    _run(
        f"""
        ALTER TABLE {table} RENAME COLUMN site_id TO site_code;
        ALTER TABLE {table} ADD COLUMN site_id integer REFERENCES sites(id);
        UPDATE {table} t SET site_id = s.id FROM sites s WHERE s.code = t.site_code;
        ALTER TABLE {table} ALTER COLUMN site_id SET NOT NULL;
        ALTER TABLE {table} DROP COLUMN site_code;
        """
    )


def _rekey_machine(table: str, nullable: bool = False, reference: bool = True) -> None:
    """machine_id text (old machines.id, now machines.code) -> machine_id bigint."""
    fk = " REFERENCES machines(id)" if reference else ""
    _run(
        f"""
        ALTER TABLE {table} RENAME COLUMN machine_id TO machine_code;
        ALTER TABLE {table} ADD COLUMN machine_id bigint{fk};
        UPDATE {table} t SET machine_id = m.id FROM machines m WHERE m.code = t.machine_code;
        """
    )
    if not nullable:
        _run(
            f"""
            DELETE FROM {table} WHERE machine_id IS NULL;
            ALTER TABLE {table} ALTER COLUMN machine_id SET NOT NULL;
            """
        )
    op.execute(f"ALTER TABLE {table} DROP COLUMN machine_code")


